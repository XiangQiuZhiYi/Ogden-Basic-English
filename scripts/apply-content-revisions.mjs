const qualities = words.filter(word => word.category.startsWith('qualities_'));
const missingForms = qualities.filter(word => !qualityForms[word.word]).map(word => word.word);
const missingExamples = qualities.filter(word => !qualityExamples[word.word]).map(word => word.word);

if (missingForms.length || missingExamples.length || Object.keys(qualityForms).length !== 150 || Object.keys(qualityExamples).length !== 150) {
  throw new Error(JSON.stringify({
    missingForms,
    missingExamples,
    formCount: Object.keys(qualityForms).length,
    exampleCount: Object.keys(qualityExamples).length,
  }));
}

const genericDefinition = definition =>
  /^A (?:thing|quality) given the name/u.test(definition)
  || definition === 'A structure word used in Basic English.';

for (const word of words) {
  word.provenance = {
    headword: 'ogden-850-order',
    ipa: 'ipa-dict-en_UK',
    definition: 'project-editorial',
    forms: 'project-editorial',
    example: 'project-editorial',
  };

  if (word.category.startsWith('qualities_')) {
    word.forms = qualityForms[word.word];
    [word.example, word.exampleZh] = qualityExamples[word.word];
    word.reviewStatus = '词形与例句已编辑 · 释义待复核';
  } else if (word.category === 'operations' && word.categoryIndex < 18) {
    word.reviewStatus = '核心用法已核验';
  } else if (!genericDefinition(word.definition)) {
    word.reviewStatus = '释义已初审 · 例句待复核';
  } else {
    word.reviewStatus = '教学内容待人工审校';
  }

  word.status = word.reviewStatus;
  if (!word.source.includes('教学内容为项目编辑')) {
    word.source += ' · 教学内容为项目编辑';
  }
}

const explicitDerivatives = {
  work: 'work · works（复数）· worker · working · worked（规则许可的派生形式）',
  surprise: 'surprise · surprises（复数）· surpriser · surprising · surprised（规则许可的派生形式）',
};
for (const [headword, forms] of Object.entries(explicitDerivatives)) {
  const word = words.find(item => item.word === headword);
  if (!word) throw new Error(`Missing derivative source word: ${headword}`);
  word.forms = forms;
}

await writeFile(wordsPath, `${JSON.stringify(words, null, 2)}\n`, 'utf8');
console.log(`Revised ${qualities.length} qualities and added provenance to ${words.length} words.`);
